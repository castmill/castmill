import { createHash } from 'node:crypto';

interface AppShellWorkerOptions {
  base: string;
  files: Array<{
    fileName: string;
    contents: string | Uint8Array;
  }>;
}

const normalizeBase = (base: string): string => {
  if (!base || base === './') {
    return '/';
  }

  const withLeadingSlash = base.startsWith('/') ? base : `/${base}`;
  return withLeadingSlash.endsWith('/')
    ? withLeadingSlash
    : `${withLeadingSlash}/`;
};

export const createAppShellWorker = ({
  base,
  files,
}: AppShellWorkerOptions): string => {
  const normalizedBase = normalizeBase(base);
  const shellFiles = files
    .filter(
      ({ fileName }) => fileName !== 'sw.js' && !fileName.endsWith('.map')
    )
    .sort(({ fileName: left }, { fileName: right }) =>
      left.localeCompare(right)
    );

  const version = createHash('sha256')
    .update(normalizedBase)
    .update(
      shellFiles
        .map(({ fileName, contents }) => {
          const contentHash = createHash('sha256')
            .update(contents)
            .digest('hex');
          return `${fileName}:${contentHash}`;
        })
        .join('|')
    )
    .digest('hex')
    .slice(0, 16);

  const shellUrls = shellFiles.map(
    ({ fileName }) => `${normalizedBase}${fileName}`
  );
  const indexUrl = `${normalizedBase}index.html`;
  const controlledPath =
    normalizedBase === '/' ? '/' : normalizedBase.slice(0, -1);

  return `/* Generated by the legacy adapter build. */
var CACHE_PREFIX = 'castmill-legacy-shell-';
var CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
var INDEX_URL = ${JSON.stringify(indexUrl)};
var CONTROLLED_PATH = ${JSON.stringify(controlledPath)};
var SHELL_URLS = ${JSON.stringify(shellUrls)};
var SHELL_PATHS = SHELL_URLS.reduce(function (paths, url) {
  paths[new URL(url, self.location.origin).pathname] = true;
  return paths;
}, {});

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      return Promise.all(
        SHELL_URLS.map(function (url) {
          return fetch(url, { credentials: 'same-origin' }).then(function (response) {
            if (!response.ok) {
              throw new Error(
                'Failed to cache app shell resource ' +
                  url +
                  ': HTTP ' +
                  response.status
              );
            }
            return cache.put(url, response);
          });
        })
      ).then(function () {
        return self.skipWaiting();
      });
    })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (cacheNames) {
      var previousShellCaches = cacheNames.filter(function (cacheName) {
        return (
          cacheName.indexOf(CACHE_PREFIX) === 0 &&
          cacheName !== CACHE_NAME
        );
      });
      var staleShellCaches = previousShellCaches.slice(
        0,
        Math.max(0, previousShellCaches.length - 1)
      );
      return Promise.all(
        staleShellCaches.map(function (cacheName) {
          return caches.delete(cacheName);
        })
      );
    }).then(function () {
      return self.clients.claim();
    })
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') {
    return;
  }
  var url = new URL(request.url);
  var isSameOrigin = url.origin === self.location.origin;

  var isLegacyNavigation =
    isSameOrigin &&
    (request.mode === 'navigate' ||
      (request.headers.get('accept') || '').indexOf('text/html') !== -1) &&
    (url.pathname === CONTROLLED_PATH ||
      url.pathname === CONTROLLED_PATH + '/' ||
      url.pathname === INDEX_URL);

  if (isLegacyNavigation) {
    event.respondWith(
      caches.open(CACHE_NAME).then(function (cache) {
        return cache.match(INDEX_URL).then(function (response) {
          return response || fetch(request);
        });
      })
    );
    return;
  }

  if (isSameOrigin && SHELL_PATHS[url.pathname]) {
    event.respondWith(
      caches.open(CACHE_NAME).then(function (cache) {
        return cache.match(request, { ignoreSearch: true }).then(function (response) {
          if (response) {
            return response;
          }
          return caches.match(request, { ignoreSearch: true }).then(function (fallback) {
            return fallback || fetch(request);
          });
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(function (response) {
      return response || fetch(request);
    })
  );
});
`;
};
